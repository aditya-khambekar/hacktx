-- Review before running as ACCOUNTADMIN in Snowsight.
-- Creates an isolated application namespace and a role that can seed/read its tables.
-- Does not modify other databases, network policy, users' passwords or MFA.
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS UNLISTED;
CREATE SCHEMA IF NOT EXISTS UNLISTED.APP;
CREATE ROLE IF NOT EXISTS UNLISTED_APP;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE UNLISTED_APP;
GRANT USAGE ON DATABASE UNLISTED TO ROLE UNLISTED_APP;
GRANT USAGE ON SCHEMA UNLISTED.APP TO ROLE UNLISTED_APP;
GRANT CREATE TABLE ON SCHEMA UNLISTED.APP TO ROLE UNLISTED_APP;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA UNLISTED.APP TO ROLE UNLISTED_APP;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA UNLISTED.APP TO ROLE UNLISTED_APP;
GRANT ROLE UNLISTED_APP TO USER SHERPCHEE;
-- After approval and successful execution, local settings will be:
-- SNOWFLAKE_DATABASE=UNLISTED
-- SNOWFLAKE_SCHEMA=APP
-- SNOWFLAKE_ROLE=UNLISTED_APP
-- Token creation and any required network-policy change are separate actions.
